while True:
    n = int(input("введите количество элементов N (4<=N<=600): "))
    if 4 <= n <= 600:
        break
    else:
        print("Ошибка: N должно быть в диапазоне от 4 до 600 включительно")
a = [int(x) for x in input(f"Введите {n} целых чисел через пробел: ").split()]
# список пиков
pk = []
# список впадин
v = []
if n < 3:
    print("Для последовательности длиной меньше 3 нельзя определить пики и впадины")
else:
    for i in range(1, n - 1):
        if a[i] > a[i - 1] and a[i] > a[i + 1]:
            pk.append((i + 1, a[i]))
        elif a[i] < a[i - 1] and a[i] < a[i + 1]:
            v.append((i + 1, a[i]))
    print("Пики(позиция,значение):", pk if pk else "нет")
    print("Впадины(позиция,значение):", v if v else "нет")
# Сумма на четных позициях и произведение на нечетных позициях
s = sum(a[1::2])
p = 1
for x in a[0::2]:
    p = p * x
print(f"Сумма элементов на четных позициях:{s}")
print(f" Произведнение элементов на нечетных позициях:{p}")
# Проверка наличия арифметической прогрессии
f = False
if n < 3:
    print("Для последовательности длиной меньше 3 прогрессия длины >=3 невозможна")
else:
    for i in range(n - 2):
        if a[i + 1] - a[i] == a[i + 2] - a[i + 1]:
            f = True
            break
    if f:
        print("Есть арифм. прогрессия длины >=3")
    else:
        print("Нет арифм.прогрессии длины >=3")
# Новый список
b = []
for i in range(n):
    t = a[i]
    if i > 0:
        t = t + a[i - 1]
    if i < n - 1:
        t = t + a[i + 1]
    b.append(t)
print("Новый список:", b)
# Поиск медианы
c = sorted(a)
if n % 2 == 1:
    md = c[n // 2]
else:
    md = (c[n // 2 - 1] + c[n // 2]) / 2
k = 0
for x in a:
    if abs(x - md) > 10:
        k = k + 1
print(f"медиана последовательности:{md}")
print(f"Количество элементов,откл. от медианы более чем на 10: {k}")
